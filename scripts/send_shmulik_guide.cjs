async function sendToShmulik() {
  const { data } = await supabase.from('settings').select('*');
  const d = data[0]?.data || {};
  const id = d.greenApiIdInstance;
  const token = d.greenApiToken;

  const chatId = '972506336896@c.us';
  const url = `https://api.green-api.com/waInstance${id}/sendMessage/${token}`;

  console.log('Sending explanation to Shmulik at', chatId, '...');
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ chatId, message: messageText })
  });

  const respData = await res.json();
  console.log('Response:', respData);
}

